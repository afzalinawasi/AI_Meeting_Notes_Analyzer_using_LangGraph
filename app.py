import pandas as pd
import streamlit as st

st.set_page_config(page_title="AI Meeting Notes Analyzer", layout="wide")

try:
    from meeting_graph import build_graph, NO_ACTION_MESSAGE, MAX_TRANSCRIPT_CHARS
except RuntimeError as error:
    st.error(str(error))
    st.stop()


@st.cache_resource
def get_graph():
    return build_graph()


app_graph = get_graph()

PROGRESS_MESSAGES = {
    "input": "Transcript validated",
    "topic_extraction": "Key topics identified",
    "meeting_summary": "Meeting summary generated",
    "action_extraction": "Action items extracted",
    "action_check": "Action items checked",
    "priority_classification": "Priorities assigned",
    "final_output": "Meeting report prepared"
}

PRIORITY_LEVELS = ["High Priority", "Medium Priority", "Low Priority"]

PRIORITY_STYLES = {
    "High Priority": "background-color: #FED0D0; color: #C30504",
    "Medium Priority": "background-color: #FEE5AD; color: #D04902",
    "Low Priority": "background-color: #C3F8EA; color: #1C8D55"
}

CARD_CLASSES = {
    "High Priority": "high",
    "Medium Priority": "medium",
    "Low Priority": "low"
}

RESULT_KEYS = ["meeting_summary", "key_topics", "action_items", "final_report"]

if "analysis_done" not in st.session_state:
    st.session_state["analysis_done"] = False

st.markdown(
    """
    <style>
    .priority-card {
        border: 1px solid #DCE3EE;
        border-left: 6px solid #DCE3EE;
        border-radius: 8px;
        padding: 12px 16px;
        background-color: #FFFFFF;
    }
    .priority-card .card-label {
        color: #384962;
        font-size: 0.9rem;
    }
    .priority-card .card-count {
        font-size: 1.8rem;
        font-weight: 600;
    }
    .priority-card.high {
        border-left-color: #C30504;
    }
    .priority-card.high .card-count {
        color: #C30504;
    }
    .priority-card.medium {
        border-left-color: #D04902;
    }
    .priority-card.medium .card-count {
        color: #D04902;
    }
    .priority-card.low {
        border-left-color: #1C8D55;
    }
    .priority-card.low .card-count {
        color: #1C8D55;
    }
    button[data-baseweb="tab"] p {
        font-size: 1.05rem;
    }
    </style>
    """,
    unsafe_allow_html=True
)


def read_uploaded_file(uploaded_file):
    try:
        return uploaded_file.getvalue().decode("utf-8")
    except UnicodeDecodeError:
        return None


def owners_in_order(items):
    owners = []
    for item in items:
        if item["owner"] not in owners:
            owners.append(item["owner"])
    return owners


def sort_by_priority(items):
    sorted_items = []
    for level in PRIORITY_LEVELS:
        for item in items:
            if item["priority"] == level:
                sorted_items.append(item)
    return sorted_items


def style_priority(value):
    return PRIORITY_STYLES.get(value, "")


def task_table(items, include_owner):
    rows = []
    for item in items:
        row = {"Task": item["task"]}
        if include_owner:
            row["Owner"] = item["owner"]
        row["Deadline"] = item["deadline"]
        row["Priority"] = item["priority"]
        rows.append(row)
    return pd.DataFrame(rows)


def table_height(row_count):
    visible_rows = min(row_count, 15)
    return (visible_rows + 1) * 35 + 3


st.image("assets/Meeting_notes_banner.png", width=2172, output_format="PNG")
st.write("Paste a transcript, upload a .txt file or use the sample, then select Analyze meeting.")

with st.expander("ⓘ Scope & Limitations"):
    st.markdown(
        """
- The app analyses English text meeting transcripts. Audio and video transcription are outside the current scope.
- Topics, summaries and action items are generated by AI and may vary slightly between runs.
- Owners are taken only from the transcript. If no owner is clearly assigned, the task shows "Not specified".
- Closely related commitments may occasionally appear as separate action items.
- Priority is assigned by fixed rules from each task's own deadline and urgency words, not from wider business impact or managerial judgement.
- The Manager Task View shows tasks from the latest analysed meeting in the current session only.
- The app does not store tasks, track completion or reassign work. Outputs should be reviewed by a person before operational use.
"""
    )

analyze_tab, report_tab, manager_tab = st.tabs(["**Analyze Meeting**", "**Meeting Report**", "**Manager Task View**"])

with analyze_tab:
    input_mode = st.radio(
        "**Choose how to provide the transcript**",
        ["Paste transcript", "Upload .txt", "Use sample transcript"],
        horizontal=True,
        key="input_mode"
    )

    transcript = ""

    if input_mode == "Paste transcript":
        transcript = st.text_area("**Meeting transcript**", height=300, key="pasted_transcript")
        st.caption("Press ⌘+Enter on Mac (Ctrl+Enter on Windows), or click outside the text box, to apply your transcript.")
    elif input_mode == "Upload .txt":
        uploaded_file = st.file_uploader("**Upload a meeting transcript**", type=["txt"])
        if uploaded_file is not None:
            file_text = read_uploaded_file(uploaded_file)
            if file_text is None:
                st.error("The file could not be read as text. Please upload a UTF-8 .txt file.")
            else:
                transcript = file_text
    else:
        with open("data/sample_transcript.txt", encoding="utf-8") as file:
            transcript = file.read()
        with st.expander("View sample transcript"):
            st.text(transcript)

    st.caption(f"{len(transcript):,} / {MAX_TRANSCRIPT_CHARS:,} characters")

    if st.button("Analyze meeting", type="primary", disabled=transcript.strip() == ""):
        st.session_state["analysis_done"] = False
        for key in RESULT_KEYS:
            if key in st.session_state:
                del st.session_state[key]

        results = {"meeting_summary": "", "key_topics": [], "action_items": [], "final_report": ""}
        error_message = ""

        with st.status("Analyzing the meeting...", expanded=True) as status:
            try:
                for update in app_graph.stream({"transcript": transcript}, stream_mode="updates"):
                    for node_name, node_output in update.items():
                        st.write(PROGRESS_MESSAGES[node_name])
                        if node_output is not None:
                            for key, value in node_output.items():
                                if key in results:
                                    results[key] = value
                status.update(label="Meeting analysis complete", state="complete")
            except ValueError as error:
                error_message = str(error)
                status.update(label="Analysis stopped", state="error")
            except Exception:
                error_message = "The analysis could not be completed. Please try again."
                status.update(label="Analysis failed", state="error")

        if error_message:
            st.error(error_message)
        else:
            for key in RESULT_KEYS:
                st.session_state[key] = results[key]
            st.session_state["analysis_done"] = True
            st.success("Meeting analysis complete. View the structured report and manager task view in the tabs above.")

with report_tab:
    if not st.session_state["analysis_done"]:
        st.info("Analyze a meeting to view the structured meeting report.")
    else:
        action_items = st.session_state["action_items"]

        st.markdown("#### 1. Meeting Summary")
        st.write(st.session_state["meeting_summary"])
        st.divider()

        st.markdown("#### 2. Key Topics")
        if len(st.session_state["key_topics"]) == 0:
            st.write("No key topics identified.")
        else:
            topic_lines = []
            for number, topic in enumerate(st.session_state["key_topics"], start=1):
                topic_lines.append(f"{number}. {topic}")
            st.markdown("\n".join(topic_lines))
        st.divider()

        st.markdown("#### 3. Action Items")
        if len(action_items) == 0:
            st.info(NO_ACTION_MESSAGE)
        else:
            report_table = task_table(action_items, include_owner=True)
            st.dataframe(report_table.style.map(style_priority, subset=["Priority"]), hide_index=True, width="stretch", height=table_height(len(action_items)))
        st.divider()

        st.markdown("#### 4. Task Owners")
        if len(action_items) == 0:
            st.info(NO_ACTION_MESSAGE)
        else:
            owner_blocks = []
            for owner in owners_in_order(action_items):
                owner_lines = [f"**Owner: {owner}**", ""]
                for item in action_items:
                    if item["owner"] == owner:
                        owner_lines.append(f"- {item['task']}")
                owner_blocks.append("\n".join(owner_lines))
            st.markdown("\n\n".join(owner_blocks))
        st.divider()

        st.markdown("#### 5. Priority Level")
        if len(action_items) == 0:
            st.info(NO_ACTION_MESSAGE)
        else:
            level_blocks = []
            for level in PRIORITY_LEVELS:
                level_tasks = []
                for item in action_items:
                    if item["priority"] == level:
                        level_tasks.append(item["task"])
                level_lines = [f"**{level} ({len(level_tasks)})**", ""]
                if len(level_tasks) == 0:
                    level_lines.append(":gray[None]")
                for task in level_tasks:
                    level_lines.append(f"- {task}")
                level_blocks.append("\n".join(level_lines))
            st.markdown("\n\n".join(level_blocks))

        st.divider()
        st.download_button(
            "Download report (.txt)",
            data=st.session_state["final_report"],
            file_name="meeting_report.txt",
            mime="text/plain"
        )
        if len(action_items) > 0:
            st.download_button(
                "Download action items (.csv)",
                data=task_table(action_items, include_owner=True).to_csv(index=False),
                file_name="action_items.csv",
                mime="text/csv"
            )

with manager_tab:
    if not st.session_state["analysis_done"]:
        st.info("Analyze a meeting to view assigned tasks by owner.")
    elif len(st.session_state["action_items"]) == 0:
        st.info(NO_ACTION_MESSAGE)
    else:
        action_items = st.session_state["action_items"]

        owner_options = ["All owners"]
        for owner in owners_in_order(action_items):
            if owner == "Not specified":
                owner_options.append("Unassigned (Not specified)")
            else:
                owner_options.append(owner)

        selected_owner = st.selectbox("**Select employee / owner**", owner_options)
        st.write("")

        if selected_owner == "All owners":
            selected_items = action_items
        else:
            owner_value = selected_owner
            if selected_owner == "Unassigned (Not specified)":
                owner_value = "Not specified"
            selected_items = []
            for item in action_items:
                if item["owner"] == owner_value:
                    selected_items.append(item)

        card_columns = st.columns(3)
        for column, level in zip(card_columns, PRIORITY_LEVELS):
            count = 0
            for item in selected_items:
                if item["priority"] == level:
                    count = count + 1
            column.markdown(
                f'<div class="priority-card {CARD_CLASSES[level]}">'
                f'<div class="card-label">{level}</div>'
                f'<div class="card-count">{count}</div>'
                f"</div>",
                unsafe_allow_html=True
            )

        st.write("")
        manager_table = task_table(sort_by_priority(selected_items), include_owner=selected_owner == "All owners")
        st.dataframe(manager_table.style.map(style_priority, subset=["Priority"]), hide_index=True, width="stretch", height=table_height(len(selected_items)))
